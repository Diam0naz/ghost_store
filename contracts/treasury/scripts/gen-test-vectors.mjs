// Generates src/test_vectors.rs: fake NEAR AI Cloud completions signed the way the TEE signs
// them (EIP-191 personal_sign over "{model}:{sha256(request)}:{sha256(response)}"), with a
// throwaway test key. Used by the unit tests of `propose_attested`.
//
// Run from the repo root after `npm install` in web/ (viem comes from there):
//   node contracts/treasury/scripts/gen-test-vectors.mjs
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { privateKeyToAccount } = await import(
  resolve(here, "../../../web/node_modules/viem/_esm/accounts/index.js")
);

// Well-known test key (Hardhat account #0). Never fund it.
const account = privateKeyToAccount(
  "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80"
);
const MODEL = "test/model";
const CREATED = 1000; // matches TS_NS in the unit tests (1000 s)
const sha256 = (s) => createHash("sha256").update(s).digest("hex");
const REQUEST_HASH = sha256("fixture-request");

const payout = (amount, rationale) => ({
  kind: { Payout: { to: "fargo", token: "danny", amount: String(amount) } },
  rationale,
});

const fixtures = {
  PAYOUT_AND_ALLOCATE: [
    payout(50, "Pay the fargo invoice due this week"),
    { kind: { Allocate: { venue: "eugene", token: "danny", amount: "100" } }, rationale: "Idle cash" },
  ],
  GOVERNANCE: [{ kind: { SetProposer: { account_id: "fargo" } }, rationale: "take over" }],
  BIG_PAYOUT: [payout(5000, "Large supplier order")],
  PAYOUT_60_A: [payout(60, "Packaging supplier")],
  PAYOUT_60_B: [payout(60, "Courier invoice")],
  PAY_INVOICE_0: [{ kind: { PayInvoice: { invoice_id: 0 } }, rationale: "Invoice FAR-1 matches the books" }],
};

let out =
  "// @generated by scripts/gen-test-vectors.mjs. Do not edit by hand.\n" +
  "// Signed with a public test key; these are NOT real NEAR AI Cloud signatures.\n\n" +
  `pub const SIGNER: &str = "${account.address.toLowerCase()}";\n` +
  `pub const MODEL: &str = "${MODEL}";\n` +
  `pub const REQUEST_HASH: &str = "${REQUEST_HASH}";\n\n`;

for (const [name, drafts] of Object.entries(fixtures)) {
  const response = JSON.stringify({
    id: `chat-${name.toLowerCase()}`,
    object: "chat.completion",
    created: CREATED,
    model: MODEL,
    choices: [
      { index: 0, message: { role: "assistant", content: JSON.stringify(drafts) }, finish_reason: "stop" },
    ],
  });
  const text = `${MODEL}:${REQUEST_HASH}:${sha256(response)}`;
  const signature = await account.signMessage({ message: text });
  out += `pub const ${name}: (&str, &str) = (\n    ${JSON.stringify(response)},\n    "${signature}",\n);\n\n`;
}

writeFileSync(resolve(here, "../src/test_vectors.rs"), out);
console.log(`wrote src/test_vectors.rs (signer ${account.address})`);
